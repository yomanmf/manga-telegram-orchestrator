import nodemailer from "nodemailer";

export function createEmailDelivery(config, createTransport = nodemailer.createTransport) {
  const transport = createTransport({
    host: config.host,
    port: config.port,
    secure: config.secure,
    auth: { user: config.user, pass: config.pass }
  });
  return {
    maxBytes: config.maxBytes,
    async deliver(volumes, title) {
      // ponytail: delivery is at-least-once; persist per-volume SMTP receipts if duplicate retries become a problem.
      for (const volume of volumes) {
        if (volume.size > config.maxBytes) throw new Error(`${volume.fileName} is too large for email delivery`);
        await transport.sendMail({
          from: config.from,
          to: config.kindleEmail,
          subject: `Manga: ${title}`,
          text: "Generated by Manga to Kindle.",
          attachments: [{ filename: volume.fileName, path: volume.filePath, contentType: "application/epub+zip" }]
        });
      }
    }
  };
}
